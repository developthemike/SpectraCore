#!/usr/bin/env python3
"""Regenerates src/gfx/colormap_data.inc.

The colour tables are committed to the repository, so this script (and
matplotlib) is only needed when the set of colour maps changes:

    python3 tools/gen_colormaps.py
"""

import pathlib

import numpy as np
from matplotlib import colormaps

ENTRIES = 256

# (name shown in the UI, key used on the command line, matplotlib name or None)
MAPS = [
    ("Turbo", "turbo", "turbo"),
    ("Inferno", "inferno", "inferno"),
    ("Magma", "magma", "magma"),
    ("Plasma", "plasma", "plasma"),
    ("Viridis", "viridis", "viridis"),
    ("Classic", "classic", None),
    ("Gray", "gray", None),
]


def classic(t):
    """The traditional SDR waterfall palette: black, blue, cyan, green, yellow, red, white."""
    stops = np.array([0.00, 0.18, 0.38, 0.55, 0.72, 0.88, 1.00])
    colours = np.array(
        [
            [0.00, 0.00, 0.05],
            [0.00, 0.05, 0.55],
            [0.00, 0.60, 1.00],
            [0.05, 0.90, 0.45],
            [0.98, 0.95, 0.05],
            [1.00, 0.20, 0.00],
            [1.00, 1.00, 1.00],
        ]
    )
    return np.stack([np.interp(t, stops, colours[:, c]) for c in range(3)], axis=1)


def gray(t):
    # Lifted slightly off black so the noise floor stays visible in 3D.
    v = 0.03 + 0.97 * t
    return np.stack([v, v, v], axis=1)


def table(mpl_name, display_name):
    t = np.linspace(0.0, 1.0, ENTRIES)
    if mpl_name is not None:
        rgb = colormaps[mpl_name](t)[:, :3]
    elif display_name == "Classic":
        rgb = classic(t)
    else:
        rgb = gray(t)
    return np.clip(np.rint(rgb * 255.0), 0, 255).astype(np.uint8)


def main():
    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "gfx" / "colormap_data.inc"
    lines = [
        "// Generated by tools/gen_colormaps.py - do not edit.",
        "//",
        "// sRGB colour tables, %d entries each.  Turbo, Inferno, Magma, Plasma and Viridis" % ENTRIES,
        "// are the matplotlib colour maps (Turbo: Apache-2.0, Google; the others: CC0).",
        "",
        "static constexpr int kColormapEntries = %d;" % ENTRIES,
        "static constexpr int kColormapCount = %d;" % len(MAPS),
        "",
        "static const char* const kColormapNames[kColormapCount] = {%s};"
        % ", ".join('"%s"' % m[0] for m in MAPS),
        "static const char* const kColormapKeys[kColormapCount] = {%s};"
        % ", ".join('"%s"' % m[1] for m in MAPS),
        "",
        "static const unsigned char kColormapData[kColormapCount][kColormapEntries][3] = {",
    ]
    for display_name, _, mpl_name in MAPS:
        rgb = table(mpl_name, display_name)
        lines.append("    {  // %s" % display_name)
        for start in range(0, ENTRIES, 8):
            chunk = ", ".join("{%3d,%3d,%3d}" % tuple(int(v) for v in c) for c in rgb[start : start + 8])
            lines.append("        %s," % chunk)
        lines.append("    },")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print("wrote %s (%d maps)" % (out, len(MAPS)))


if __name__ == "__main__":
    main()
